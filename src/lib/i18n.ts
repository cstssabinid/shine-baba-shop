export function localizeProduct(product: Product, locale: Locale): Product {
  if (locale === "en") return product;
  return { ...product, ...productText[locale][product.slug] };
}

export function getProductTranslation(slug: string, locale: Exclude<Locale, "en">): Partial<Product> {
  return productText[locale][slug] ?? {};
}

export function localizeCategory(name: string, locale: Locale): string {
  return translate(locale, name);
}

export function localizeOption(product: Product, value: string | undefined, locale: Locale): string | undefined {
  if (!value || locale === "en" || !product.options) return value;
  const index = product.options.values.indexOf(value);
  return index < 0 ? value : localizeProduct(product, locale).options?.values[index] ?? value;
}
